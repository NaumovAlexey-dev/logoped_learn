import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Начать обучение/ }).click()
await page.locator('.choice').filter({ hasText: 'Стёртая дизартрия' }).click()
await page.locator('.action-bar .btn').click()
await page.waitForTimeout(350)
const box = await page.locator('.lesson__actions').boundingBox()
console.log('actions box:', box, 'viewport 844')
await page.screenshot({ path: 'shots/18-lesson-tight.png', fullPage: false })
await browser.close()
