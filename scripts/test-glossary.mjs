import { chromium } from 'playwright'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 })
const errors = []
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
page.on('pageerror', e => errors.push(e.message))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Словарь терминов' }).click()
await page.waitForTimeout(300)
console.log('modal:', await page.getByRole('heading', { name: 'Словарь терминов' }).isVisible())
console.log('entries:', await page.locator('.glossary-card').count())
await page.getByLabel('Поиск по словарю терминов').fill('ОНР')
await page.waitForTimeout(200)
console.log('filtered:', await page.locator('.glossary-card').count())
console.log('first:', (await page.locator('.glossary-card').first().innerText()).replace(/\n/g, ' | '))
await page.screenshot({ path: 'shots/39-glossary-modal.png', fullPage: false })
await page.getByRole('button', { name: 'Закрыть' }).click()
await page.getByRole('button', { name: 'Теория', exact: true }).click()
await page.getByRole('tab', { name: 'Словарь' }).click()
await page.waitForTimeout(200)
console.log('theory glossary cards:', await page.locator('.glossary-card').count())
await page.screenshot({ path: 'shots/40-glossary-tab.png', fullPage: false })
console.log('errors:', errors.length ? errors : 'none')
await browser.close()
